fn ru_plural(n: u64) -> usize {
    match (n % 10, n % 100) {
        (1, r) if r != 11 => 0,
        (2..=4, r) if !(12..=14).contains(&r) => 1,
        _ => 2,
    }
}

fn en_plural(n: u64) -> usize {
    if n == 1 { 0 } else { 1 }
}

impl Tr {
    /// "labels" agreeing with `n`.
    pub fn labels(&self, n: u64) -> &'static str {
        self.labels[(self.plural)(n)]
    }
}

pub fn tr(lang: Lang) -> &'static Tr {
    match lang {
        Lang::Ru => &RU,
        Lang::En => &EN,
    }
}
